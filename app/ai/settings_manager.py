"""
Runtime-selectable AI provider/model - same in-memory-singleton pattern as
app/core/trading_mode.py's trading_mode_manager. Changeable from the
frontend (Settings modal -> PUT /api/ai-settings) without a server
restart; resets to the .env default (settings.ai_provider) on restart,
same as every other "runtime mode" in this app.

`analysis_enrichment_enabled` gates whether the AI Analysis page's
scenario narrative is generated by an LLM at all -- it defaults to False
so a fresh install behaves EXACTLY as before this feature existed
(deterministic rule_based_scenario_fallback only) until the user
explicitly opts in. This also means turning it on is a deliberate choice
to start spending API credits on every analysis refresh (see
signal_service.py's caching for how that cost is bounded).
"""
from dataclasses import dataclass

VALID_PROVIDERS = ("anthropic", "gemini", "openai")


@dataclass
class AISettingsState:
    provider: str
    model: str | None  # None = provider's own default model
    analysis_enrichment_enabled: bool


class AISettingsManager:
    def __init__(self, default_provider: str = "gemini"):
        self._state = AISettingsState(
            provider=default_provider if default_provider in VALID_PROVIDERS else "gemini",
            model=None,
            analysis_enrichment_enabled=False,
        )

    @property
    def state(self) -> AISettingsState:
        return self._state

    def set_provider(self, provider: str, model: str | None = None) -> AISettingsState:
        if provider not in VALID_PROVIDERS:
            raise ValueError(f"Unknown provider '{provider}'. Must be one of {VALID_PROVIDERS}.")
        self._state.provider = provider
        self._state.model = model or None
        return self._state

    def set_analysis_enrichment(self, enabled: bool) -> AISettingsState:
        self._state.analysis_enrichment_enabled = enabled
        return self._state


def _default_provider() -> str:
    # Deferred import to avoid a hard dependency at module-import time.
    from app.config import get_settings

    return get_settings().ai_provider


ai_settings_manager = AISettingsManager(default_provider=_default_provider())
